// ============================================================
// SG90 舵机驱动（模拟窗户开关）
// ============================================================
// 引脚: PA6 (TIM3_CH1 PWM)
// 参数: 20ms周期(50Hz), 500~2500µs脉宽对应 0°~180°
// 公式: pulse = 500 + angle × (2000 / 180)
//
// 系统中舵机用作"模拟窗户"：
//   正常/预警: 0° (关闭窗户)
//   告警:     90° (打开窗户通风排烟)
//   手动模式: 远程可设定任意角度
// ============================================================

#include "stm32f10x.h"
#include "pwm.h"

// ---- 舵机初始化（委托PWM初始化）----
void Servo_Init(void)
{
    PWM_Servo_Init();  // TIM3_CH1, 20ms周期, 50Hz
}

// ---- 设置舵机角度(0~180°) ----
// 角度→脉宽转换：500µs=0°, 2500µs=180°, 线性插值
void Servo_SetAngle(uint16_t Angle)
{
    if (Angle > 180) Angle = 180;

    // 角度线性映射到脉宽：500 + angle × (2000/180) ≈ 500 + angle×11.11
    uint16_t pulse = 500 + (uint16_t)((float)Angle * 2000 / 180);

    PWM_Servo_SetCompare2(pulse);  // 设置CCR2比较值
}
